using System;

namespace DotGram.Grammar.Emit;

/// <summary>
/// Sources the generator emits into the user's compilation. .Gram ships no runtime
/// assembly: everything a generated parser needs is emitted next to it.
/// </summary>
/// <remarks>
/// <para>
/// <b>Default mode</b> — support types are emitted <c>internal</c>, so nothing
/// crosses an assembly boundary and there is no dependency to version.
/// </para>
/// <para>
/// <b>Shared mode</b> — an assembly marked <c>[assembly: GramRuntime]</c> emits the
/// same types <c>public</c>. Assemblies referencing it reuse those instead of
/// emitting their own, which is what makes a .Gram parser exposable in a public API.
/// </para>
/// <para>
/// The two modes are strictly additive: opting in adds typed overloads, it never
/// changes an existing signature.
/// </para>
/// </remarks>
public static class SupportEmitter
{
	/// <summary>Marker attributes. Always <c>internal</c>, always emitted, in every assembly.</summary>
	/// <remarks>
	/// Emitted from post-initialization, before any compilation analysis, so that
	/// <c>[Gram]</c> and <c>[assembly: GramRuntime]</c> can be written in source at all.
	/// </remarks>
	public const string Attributes = """
		// <auto-generated/>
		#nullable enable

		namespace DotGram
		{
			/// <summary>Marks a partial class as the host of a grammar.</summary>
			[global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
			[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
			internal sealed class GramAttribute : global::System.Attribute
			{
				public GramAttribute() { }

				/// <param name="source">
				/// A path to a .gram file, or the grammar text itself. A single-line value
				/// ending in ".gram" is a path; anything else is grammar text.
				/// </param>
				public GramAttribute(string source) => Source = source;

				public string? Source { get; }
			}

			/// <summary>
			/// Declares that this assembly publishes the shared .Gram support types.
			/// Referencing assemblies bind to them instead of emitting their own.
			/// </summary>
			[global::System.AttributeUsage(global::System.AttributeTargets.Assembly, AllowMultiple = false)]
			[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
			internal sealed class GramRuntimeAttribute : global::System.Attribute
			{
			}
		}
		""";

	/// <summary>Support types, emitted with the given accessibility.</summary>
	public static string SupportTypes(SupportAccessibility accessibility)
	{
		var access = accessibility == SupportAccessibility.Public ? "public" : "internal";

		return $$"""
		// <auto-generated/>
		#nullable enable

		namespace DotGram
		{
			/// <summary>How a recognizer finished. Ordinary values, never exceptions.</summary>
			{{access}} enum Outcome
			{
				/// <summary>A value was recognized.</summary>
				Success,

				/// <summary>The construct does not begin here; a sibling alternative may be tried.</summary>
				NoMatch,

				/// <summary>The construct appeared to begin but is malformed.</summary>
				Error,
			}

			/// <summary>Half-open range of input items: [Start, End).</summary>
			{{access}} readonly struct SourceSpan : global::System.IEquatable<SourceSpan>
			{
				public SourceSpan(int start, int length)
				{
					Start  = start;
					Length = length;
				}

				public int Start  { get; }
				public int Length { get; }
				public int End    => Start + Length;

				public bool IsEmpty => Length == 0;

				public static SourceSpan FromBounds(int start, int end) => new SourceSpan(start, end - start);

				public bool Equals(SourceSpan other) => Start == other.Start && Length == other.Length;

				public override bool Equals(object? obj) => obj is SourceSpan other && Equals(other);

				public override int GetHashCode() => unchecked((Start * 397) ^ Length);

				public override string ToString() => "[" + Start + ".." + End + ")";

				public static bool operator ==(SourceSpan left, SourceSpan right) =>  left.Equals(right);
				public static bool operator !=(SourceSpan left, SourceSpan right) => !left.Equals(right);
			}

			/// <summary>What went wrong, and where.</summary>
			{{access}} sealed class Diagnostic
			{
				public Diagnostic(string message, SourceSpan span)
				{
					Message = message;
					Span    = span;
				}

				public string     Message { get; }
				public SourceSpan Span    { get; }

				public override string ToString() => Span + ": " + Message;
			}

			/// <summary>Result of one recognizer invocation.</summary>
			{{access}} readonly struct RecognitionResult<T>
			{
				private RecognitionResult(Outcome outcome, T? value, SourceSpan span, Diagnostic? diagnostic)
				{
					Outcome    = outcome;
					Value      = value;
					Span       = span;
					Diagnostic = diagnostic;
				}

				public Outcome     Outcome    { get; }
				public T?          Value      { get; }
				public SourceSpan  Span       { get; }
				public Diagnostic? Diagnostic { get; }

				public bool IsSuccess => Outcome == Outcome.Success;

				public static RecognitionResult<T> Success(T value, SourceSpan span) =>
					new RecognitionResult<T>(Outcome.Success, value, span, null);

				public static RecognitionResult<T> NoMatch(SourceSpan span) =>
					new RecognitionResult<T>(Outcome.NoMatch, default, span, null);

				public static RecognitionResult<T> Error(Diagnostic diagnostic) =>
					new RecognitionResult<T>(Outcome.Error, default, diagnostic.Span, diagnostic);
			}
		}
		""";
	}
}
