/// <summary>Indent-aware output. One per generated function, so nothing interleaves.</summary>
sealed class Writer(int depth)
{
	readonly StringBuilder _text = new();

	int _depth = depth;

	/// <summary>How far in the next line will be written — what a nested writer starts at.</summary>
	public int Depth => _depth;

	public void Line(string text = "")
	{
		if (text.Length == 0)
			_text.EndLine();
		else
			_text.Append('\t', _depth).AppendEndingWith(text);
	}

	/// <summary>A single indented line — the body of an <c>if</c> without braces.</summary>
	public void Then(string text)
	{
		_depth++;
		Line(text);
		_depth--;
	}

	public IDisposable Block(string header)
	{
		Line(header);
		Line("{");
		_depth++;

		return new Closer(this);
	}

	/// <summary>Indents what follows, without braces around it — a switch section.</summary>
	public IDisposable Indent()
	{
		_depth++;

		return new Outdenter(this);
	}

	public void Append(Writer other) => _text.Append(other._text);

	/// <summary>
	/// Writes text that is already laid out, each line at the current depth.
	/// </summary>
	/// <remarks>
	/// The endings are normalized first, and that is not tidiness. What arrives here is a
	/// raw string literal, whose content is whatever the file it was typed in was saved
	/// with — so a generator whose own source went from CRLF to LF would silently start
	/// emitting every one of these blocks as a single unsplit line, indented once and
	/// flattened after that. Generated code must not depend on how the generator was
	/// saved.
	/// </remarks>
	public void Write(string text)
	{
		var written = new Writer(0);

		written._text.Append(Lines.Normalize(text));

		// AppendIndented reads the text as lines, each closed by an ending. Text that
		// does not end with one — a raw string literal, say — would lose its last line.
		if (!text.EndsWith(Lines.Ending, StringComparison.Ordinal))
			written._text.Append(Lines.Ending);

		AppendIndented(written, 0);
	}

	/// <summary>Appends another writer's text, shifted in to this one's depth.</summary>
	public void AppendIndented(Writer other, int extra = 1)
	{
		var lines = other._text.ToString().Split([Lines.Ending], StringSplitOptions.None);

		// The text ends with an ending, so the split leaves a final empty piece that is
		// not a line at all.
		for (var i = 0; i < lines.Length - 1; i++)
			if (lines[i].Length > 0)
				_text.Append('\t', _depth + extra).AppendEndingWith(lines[i]);
			else
				_text.EndLine();
	}

	public override string ToString() => _text.ToString();

	sealed class Closer(Writer writer) : IDisposable
	{
		public void Dispose()
		{
			writer._depth--;
			writer.Line("}");
		}
	}

	sealed class Outdenter(Writer writer) : IDisposable
	{
		public void Dispose() => writer._depth--;
	}
}

/// <summary>
/// Turns a recognition graph into C#.
/// </summary>
/// <remarks>
/// <para>
/// One method per rule, and inside it a state machine — see <see cref="Machine"/>, which
/// says why it is one rather than a function per node. Every recognizer has the same
/// shape, take the input and a position and return the new position or -1, so composing
/// them is calling them: nothing allocated, nothing virtual, no closure. A rule of
/// binding powers takes one more argument, and only that kind does (§4.3.1).
/// </para>
/// <para>
/// What this file is responsible for is everything around the machines — the published
/// methods, the result types, the factories a <c>=&gt;</c> becomes, the support types
/// shared with the machines, and the layout of the file they all go in. The machines
/// themselves are compiled by <see cref="Machine"/>.
/// </para>
/// <para>
/// The text produced here is compiled in the consumer's project, which is a different
/// set of rules from this assembly's own: see .claude/rules/emitted-code.md.
/// </para>
/// </remarks>
public static class CSharpEmitter
{
	/// <param name="graph">The normalized grammar.</param>
	/// <param name="className">
	/// The partial class the generated members go into. A nested host is named by its
	/// chain — <c>Outer.Inner</c> — and written back out nested.
	/// </param>
	/// <param name="namespace">Its namespace, or null for the global one.</param>
	public static string Emit(RecognitionGraph graph, string className, string? @namespace = null)
	{
		if (graph is null)
			throw new ArgumentNullException(nameof(graph));

		var file    = new Writer(0);
		var scope   = new Stack<IDisposable>();
		var results = new ResultTypes(graph, className, @namespace);

		file.Line("// <auto-generated/>");
		file.Line("#nullable enable");
		file.Line();

		// A block namespace rather than a file-scoped one: the consumer's language
		// version is unknown (.claude/rules/emitted-code.md).
		if (@namespace is not null)
			scope.Push(file.Block($"namespace {@namespace}"));

		// The grammar's own `@using` directives and no others. Everything this file
		// generates is written with `global::`; these are here for the C# the grammar
		// supplied, which was written expecting them (§1).
		if (graph.CSharpImports.Count > 0)
		{
			foreach (var import in graph.CSharpImports)
				file.Line($"using {import};");

			file.Line();
		}

		foreach (var name in className.Split('.'))
			scope.Push(file.Block($"partial class {name}"));

		foreach (var publication in graph.Publications)
		{
			EmitPublication(
				file,
				publication,
				results,
				graph.Climbing.ContainsKey(publication.Rule),
				Streams(graph, publication));

			file.Line();
		}

		foreach (var rule in results.Built)
		{
			EmitResultType(file, graph, results, rule);
			file.Line();
		}

		foreach (var rule in graph.Rules)
		{
			if (!graph.Types.ContainsKey(rule))
				continue;

			foreach (var factory in FactoriesOf(graph, results, rule))
			{
				EmitFactory(file, graph, rule, factory, results);
				file.Line();
			}
		}

		var needsStack = false;

		// `parse` demands the input end. Asking the rule and then checking would leave it
		// unable to go back for a longer match — the check has to be inside the machine,
		// where failing it is an ordinary failure and the stack still has somewhere to
		// resume. So the rule's body is compiled again, with end-of-input on the end.
		foreach (var publication in graph.Publications)
		{
			if (publication.Kind != PublishKind.Parse)
				continue;

			var whole = new Machine(
				WholeOf(publication.Rule), results, BuiltBy(graph, results, publication.Rule))
			{
				Reaches    = graph.Recoveries.Count > 0,
				Refuses    = Refusing(graph),
				TakesPower = graph.Climbing.ContainsKey(publication.Rule),
			};

			// The same body compiled a second time, so it climbs the same way. Publication
			// asks at strength 0, which admits every alternative.
			whole.Climbs(
				graph.Climbing,
				graph.Powers,
				graph.Climbing.TryGetValue(publication.Rule, out var climbed)
					? climbed
					: new Dictionary<Node, int>());

			// A rule that recovers recovers however it is entered. The whole-input machine is
			// the same body compiled a second time, so it is told the same thing — and calls
			// the one factory, which the rule's own machine emits.
			if (RecoveryIn(graph, results, publication.Rule) is var (repeats, recovers, into))
				whole.Recovers(repeats, recovers, into, MethodOf(publication.Rule) + "_Recover");

			// The two ends normalization cannot reach: it inserts Trivia between operands,
			// and a whole parse has an outside (§4.5).
			var body = graph.Trivia.TryGetValue(publication.Rule, out var trivia)
				? new Node.Sequence([trivia, graph.Bodies[publication.Rule], trivia, EndOfInput])
				: new Node.Sequence([graph.Bodies[publication.Rule], EndOfInput]);

			file.Write(whole.Render(
				whole.Compile(body, Machine.Accept),
				$"parse {publication.Rule.Name}: {graph.Bodies[publication.Rule]} & eof"));
			file.Line();

			foreach (var extra in whole.Extra)
			{
				file.Write(extra);
				file.Line();
			}

			// §6.3 over a reader. The parts that are not calls — `eof`, a separator, the
			// Trivia normalization inserted — have no recognizer of their own, so each gets
			// one: the driver runs them in order and they have to be runnable one at a time.
			if (Streams(graph, publication) && StagesOf(graph, publication.Rule) is { } stages)
			{
				var parts = new List<string>(stages.Count);

				for (var i = 0; i < stages.Count; i++)
				{
					if (stages[i].Rule is not null)
					{
						parts.Add("");

						continue;
					}

					var part = new Machine($"{WholeOf(publication.Rule)}_Part{i}", results);

					file.Write(part.Render(
						part.Compile(stages[i].Node, Machine.Accept),
						$"one part of a streamed {publication.Rule.Name}: {stages[i].Node}"));

					file.Line();
					parts.Add(part.Name);
				}

				// What the repetition was told to do about a bad element, and where the
				// parse may pick up again — compiled here rather than inside a machine,
				// because in a stream it is the driver that steps over one.
				var found   = RecoveryIn(graph, results, publication.Rule);
				var sync    = (string?)null;
				var factory = MethodOf(publication.Rule) + "_Recover";

				if (found is var (_, recovered, _) && recovered.Sync is { } expression)
				{
					var machine = new Machine($"{WholeOf(publication.Rule)}_Sync", results)
					{
						IsLookahead = true,
					};

					file.Write(machine.Render(
						machine.Compile(expression, Machine.Accept),
						$"where a streamed {publication.Rule.Name} picks up again: {expression}"));

					file.Line();
					sync = machine.Name;
				}

				EmitStreamingParse(
					file, graph, publication, results, stages, parts,
					found?.Recovery, sync, factory);
				file.Line();
			}

			needsStack = true;
		}

		foreach (var rule in graph.Rules)
		{
			needsStack |= EmitRule(file, graph, results, rule);
			file.Line();
		}

		if (graph.Publications.Count > 0)
		{
			file.Write(MatchStruct);
			file.Line();
		}

		if (graph.Rules.Count > 0)
		{
			file.Write(FailureStructWith(graph.Recoveries.Count > 0, Refusing(graph)));
			file.Line();
		}

		if (Streaming(graph))
		{
			file.Write(WindowClass);
			file.Line();
			file.Write(LinesClass);
			file.Line();
		}

		if (Reporting(graph))
		{
			file.Write(RecoveredHook);
			file.Line();
		}

		if (Locating(graph))
		{
			file.Write(LocateHelper);
			file.Line();
		}

		if (needsStack)
			file.Write(GrowHelper);

		while (scope.Count > 0)
			scope.Pop().Dispose();

		return file.ToString();
	}

	/// <summary>
	/// One directive (docs/syntax.md §6). <c>parse</c> makes an asserting method and an
	/// asking one; <c>find</c> makes a sequence.
	/// </summary>
	/// <remarks>
	/// No <c>out</c> parameters anywhere: what a match has to say goes in
	/// <see cref="MatchType"/>, where the next thing it has to say is a field rather than
	/// another parameter on every signature.
	/// </remarks>
	static void EmitPublication(
		Writer file, Publication publication, ResultTypes results, bool climbs, bool streams)
	{
		var method = publication.MethodName;
		var name   = publication.Rule.Name;
		var built  = results.QualifiedOf(publication.Rule);
		var value  = built ?? "string";
		var match  = $"{MatchType}<{value}>";

		// A rule that builds hands its value back through the recognizer; one that does
		// not leaves the extent it matched, and the text is cut from the input.
		// A rule of binding powers is asked at strength 0, which admits all of it (§4.3.1).
		var hands = (climbs ? ", 0" : "") +
			(built is null ? ", ref failure" : ", ref failure, out var recognized");

		string Recognized(string from, string to) =>
			built is null ? $"input.Substring({from}, {to})" : "recognized";

		if (publication.Kind == PublishKind.Find)
		{
			EmitFind(file, publication, method, name, value, match, hands, Recognized);

			if (streams)
			{
				file.Line();

				EmitStreamingFind(file, publication, method, name, match, hands, built is not null);
			}

			return;
		}

		file.Line($"/// <summary>Parses the whole input as <c>{name}</c>.</summary>");
		file.Line("/// <exception cref=\"global::System.FormatException\">");
		file.Line($"/// The input is not <c>{name}</c>. <c>Try{method}</c> answers instead.");
		file.Line("/// </exception>");

		using (file.Block($"public static {value} {method}(string input)"))
		{
			file.Line($"var match = Try{method}(input);");
			file.Line();
			file.Line("if (match.IsSuccess)");
			file.Then("return match.Value;");
			file.Line();
			file.Line("throw new global::System.FormatException(match.Error + \" at \" + match.Position.ToString());");
		}

		file.Line();
		file.Line($"/// <summary>Parses the whole input as <c>{name}</c>, answering rather than throwing.</summary>");

		using (file.Block($"public static {match} Try{method}(string input)"))
		{
			// Fully qualified, and as a static call rather than an extension method:
			// the emitted file carries no usings at all (.claude/rules/emitted-code.md).
			file.Line("var text    = global::System.MemoryExtensions.AsSpan(input);");

			// Carried through every recognizer this call reaches, so that what comes back
			// is the furthest the input was followed and not merely "no".
			file.Line($"var failure = new {FailureType}();");
			file.Line();
			file.Line($"var end = {WholeOf(publication.Rule)}(text, 0{hands});");
			file.Line();
			file.Line("if (end < 0)");
			file.Then($"return {match}.Failed(\"Input does not match '{name}'.\", failure.Position);");
			file.Line();
			file.Line($"return {match}.Success({Recognized("0", "end")}, 0, end);");
		}
	}

	/// <summary>
	/// <c>find</c>: every occurrence, one at a time.
	/// </summary>
	/// <remarks>
	/// An iterator rather than an array, so that a document with a million occurrences
	/// costs one at a time — and so that "the first one" and "the ones that satisfy this"
	/// are LINQ's rather than three more directives. The span is made where it is passed
	/// and never held in a local, which is what lets this be an iterator at all.
	/// </remarks>
	static void EmitFind(
		Writer file, Publication publication, string method, string name,
		string value, string match, string hands, Func<string, string, string> recognized)
	{
		file.Line($"/// <summary>Every occurrence of <c>{name}</c>, in order, found as it is asked for.</summary>");

		using (file.Block(
			$"public static global::System.Collections.Generic.IEnumerable<{match}> {method}(string input)"))
		{
			using (file.Block("for (var start = 0; start <= input.Length; )"))
			{
				file.Line($"var failure = new {FailureType}();");
				file.Line();
				file.Line(
					$"var end = {MethodOf(publication.Rule)}(" +
					$"global::System.MemoryExtensions.AsSpan(input), start{hands});");
				file.Line();

				using (file.Block("if (end < 0)"))
				{
					file.Line("start++;");
					file.Line("continue;");
				}

				file.Line();
				file.Line($"yield return {match}.Success({recognized("start", "end - start")}, start, end - start);");
				file.Line();
				file.Line("// A rule that matches nothing would otherwise find it for ever.");
				file.Line("start = end > start ? end : start + 1;");
			}
		}
	}

	/// <summary>
	/// <c>find</c> over a reader: the same occurrences, out of input that is never all
	/// there at once.
	/// </summary>
	/// <remarks>
	/// <para>
	/// The same loop as the one over a string, with one thing added: a result that ran
	/// into the end of the window is not an answer yet. The input could have carried it
	/// further — <c>['0'..'9']+</c> stopped at a buffer boundary is two occurrences where
	/// there is one — and a failure that reached the end could have matched. So anything
	/// that touches the end is provisional while the reader has more, and the window is
	/// read into and the question asked again from the same place.
	/// </para>
	/// <para>
	/// That is also what keeps <c>eof</c> honest: the end of a full buffer looks exactly
	/// like the end of the input to a recognizer, and the only thing that can tell them
	/// apart is whether the reader is finished.
	/// </para>
	/// </remarks>
	static void EmitStreamingFind(
		Writer file, Publication publication, string method, string name,
		string match, string hands, bool builds)
	{
		var recognized = builds ? "recognized" : "window.Text(start, end - start)";

		file.Line($"/// <summary>Every occurrence of <c>{name}</c> in a reader, read as it is asked for.</summary>");
		file.Line("/// <remarks>");
		file.Line("/// The input is read through a buffer that is reused, so what is held is what the");
		file.Line($"/// occurrence being read needs and not the input (docs/syntax.md §6.3).");
		file.Line("/// </remarks>");

		using (file.Block(
			$"public static global::System.Collections.Generic.IEnumerable<{match}> {method}(" +
			"global::System.IO.TextReader input)"))
		{
			file.Line($"var window = new {WindowType}(input, {WindowSize});");
			file.Line("var start  = 0;");
			file.Line();

			using (file.Block("while (true)"))
			{
				file.Line($"var failure = new {FailureType}();");
				file.Line();
				file.Line($"var end = {MethodOf(publication.Rule)}(window.Span(), start{hands});");
				file.Line();

				// Reaching the end of what is held is not the same as reaching the end of the
				// input, and only the reader knows which one it was.
				using (file.Block(
					"if ((end < 0 ? failure.Position : end) >= window.Length && !window.Ended)"))
				{
					file.Line("window.Extend(ref start);");
					file.Line("continue;");
				}

				file.Line();

				using (file.Block("if (end < 0)"))
				{
					file.Line("if (start >= window.Length)");
					file.Then("yield break;");
					file.Line();
					file.Line("start++;");
					file.Line("continue;");
				}

				file.Line();
				file.Line(
					$"yield return {match}.Success({recognized}, window.Offset + start, end - start);");
				file.Line();
				file.Line("// A rule that matches nothing would otherwise find it for ever.");
				file.Line("start = end > start ? end : start + 1;");
				file.Line();
				file.Line("if (start > window.Length)");
				file.Then("yield break;");
			}
		}

		file.Line();

		EmitOverLines(file, $"global::System.Collections.Generic.IEnumerable<{match}>", method, name);
	}

	/// <summary>
	/// The same method again, taking lines rather than a reader (§6.3).
	/// </summary>
	/// <remarks>
	/// One line, because a sequence of lines is a reader once the terminators are put
	/// back. Written out rather than left to the caller so that <c>File.ReadLines</c> and
	/// a <c>List&lt;string&gt;</c> are as ordinary an input as a string is.
	/// </remarks>
	static void EmitOverLines(Writer file, string returns, string method, string name)
	{
		file.Line($"/// <summary>The same, over a sequence of lines (docs/syntax.md §6.3).</summary>");
		file.Line("/// <remarks>");
		file.Line("/// The lines are read as though they were a file, with a newline put back on the");
		file.Line($"/// end of each: a sequence of lines has had its terminators taken off, and <c>{name}</c>");
		file.Line("/// may well be looking for one.");
		file.Line("/// </remarks>");

		using (file.Block(
			$"public static {returns} {method}(" +
			"global::System.Collections.Generic.IEnumerable<string> input)"))
		{
			file.Line($"return {method}(new {LinesType}(input));");
		}
	}

	/// <summary>
	/// Whether this publication gets a reader overload (§6.3).
	/// </summary>
	/// <remarks>
	/// <c>find</c> only, for now. It is the directive the analysis has least to prove
	/// about: an occurrence is looked for and then handed over, so the window may move at
	/// every one of them, and all that is left to ask is whether one occurrence fits in a
	/// window at all. <c>parse</c> needs the decomposition <see cref="Retention.PlanFor"/>
	/// does, because what lets it move is a committed repetition in the middle of it.
	/// </remarks>
	/// <summary>
	/// <c>parse</c> over a reader: the rule's parts, handed over as they are read.
	/// </summary>
	/// <remarks>
	/// <para>
	/// The stages are run in order rather than compiled into one machine, and that is the
	/// whole difference from the parse over a string. A machine may backtrack anywhere
	/// inside the rule; a stream may not go back past what it has handed over. What makes
	/// the two agree is the mark: §8.2's <c>recover</c> is possessive, so the repetition in
	/// the middle never wants to give an element back, and the stages around it are read
	/// once each.
	/// </para>
	/// <para>
	/// Each stage reads through the window with the same provisional rule <c>find</c> uses:
	/// a result that ran into the end of what is held is not an answer while the reader has
	/// more.
	/// </para>
	/// </remarks>
	static void EmitStreamingParse(
		Writer file, RecognitionGraph graph, Publication publication, ResultTypes results,
		IReadOnlyList<Stage> stages, IReadOnlyList<string> parts,
		Recovery? recovery, string? sync, string factory)
	{
		var element = graph.Types[publication.Rule];

		element = element.Substring(0, element.Length - "[]".Length);

		file.Line($"/// <summary>Reads <c>{publication.Rule.Name}</c> from a reader, a part at a time.</summary>");
		file.Line("/// <remarks>");
		file.Line("/// The input is read through a buffer that is reused, so what is held is the part");
		file.Line("/// being read and not the input. Each element is handed over as it is read, which");
		file.Line("/// is why the repetition has to be marked 'recover' (docs/syntax.md §6.3, §8.2).");
		file.Line("/// </remarks>");

		using (file.Block(
			$"public static global::System.Collections.Generic.IEnumerable<{element}> " +
			$"{publication.MethodName}(global::System.IO.TextReader input)"))
		{
			file.Line($"var window = new {WindowType}(input, {WindowSize});");
			file.Line("var start  = 0;");

			for (var i = 0; i < stages.Count; i++)
			{
				var stage  = stages[i];
				var method = stage.Rule is { } rule ? MethodOf(rule) : parts[i];
				var built  = stage.Rule is { } called ? results.QualifiedOf(called) : null;

				file.Line();
				file.Line("// " + Comment(stage));

				// Outside the loop, because it counts the elements of the whole repetition
				// and a rejected one holds its place in the numbering (§8.2).
				if (stage.Repeated && recovery is not null)
					file.Line($"var ordinal{i} = 0;");

				var loop = stage.Repeated ? file.Block("while (true)") : null;

				Read(i, stage, method, built);

				loop?.Dispose();
			}

			// Names per stage rather than one set reused: a stage that is not a repetition
			// declares its locals in the method's own scope, and two of them cannot share.
			void Read(int i, Stage stage, string method, string? built)
			{
				var hands = built is null ? "ref failure" + i : $"ref failure{i}, out value{i}";

				file.Line($"var failure{i} = new {FailureType}();");

				if (built is not null)
					file.Line($"{built} value{i} = default!;");

				file.Line($"int end{i};");
				file.Line();

				using (file.Block("while (true)"))
				{
					file.Line($"failure{i} = new {FailureType}();");
					file.Line($"end{i}     = {method}(window.Span(), start, {hands});");
					file.Line();

					// The same provisional rule `find` reads by: what ran into the end of the
					// window is not an answer while the reader has more.
					using (file.Block(
						$"if ((end{i} < 0 ? failure{i}.Position : end{i}) >= window.Length && !window.Ended)"))
					{
						file.Line("window.Extend(ref start);");
						file.Line("continue;");
					}

					file.Line();
					file.Line("break;");
				}

				file.Line();

				if (stage.Repeated && recovery is not null)
				{
					// §8.2 in a stream. An element that never began ends the repetition; one
					// that began and broke is an error to step over, and where to pick up
					// again is the synchronization expression — looked for in the window,
					// reading more of it when the search runs out of what is held.
					using (file.Block($"if (end{i} < 0)"))
					{
						file.Line($"if (failure{i}.Reach <= start)");
						file.Then("break;");
						file.Line();
						file.Line("var from = start;");
						file.Line("var to   = start;");
						file.Line("var at   = -1;");
						file.Line();

						using (file.Block("while (true)"))
						{
							using (file.Block("while (to <= window.Length)"))
							{
								file.Line($"at = {sync}(window.Span(), to);");
								file.Line();
								file.Line("if (at > to)");
								file.Then("break;");
								file.Line();
								file.Line("at = -1;");
								file.Line("to++;");
							}

							file.Line();
							file.Line("if (at >= 0 || window.Ended)");
							file.Then("break;");
							file.Line();

							// Extended from `from` and not from `start`: what is being
							// looked for is where this element ends, and the element
							// begins at `from`. Dropping to `start` would throw away the
							// front of the very thing about to be handed over — and put
							// `from` before the window, which is nowhere.
							file.Line("var ahead = to - from;");
							file.Line("var after = start - from;");
							file.Line();
							file.Line("window.Extend(ref from);");
							file.Line();
							file.Line("start = from + after;");
							file.Line("to    = from + ahead;");
						}

						file.Line();
						file.Line("if (at < 0)");
						file.Then("to = at = window.Length;");
						file.Line();

						EmitStreamedRejection(
							file, graph, publication, recovery, factory, i, Named(stage));

						file.Line("start = at;");
						file.Line("continue;");
					}
				}
				else if (stage.Repeated)
				{
					file.Line($"if (end{i} < 0)");
					file.Then("break;");
				}
				else
				{
					file.Line($"if (end{i} < 0)");
					file.Then(
						"throw new global::System.FormatException(" +
						$"\"Input does not match '{Named(stage)}' at \" + " +
						$"(window.Offset + failure{i}.Position).ToString(" +
						"global::System.Globalization.CultureInfo.InvariantCulture) + \".\");");
				}

				file.Line();

				if (built is not null)
					file.Line($"yield return value{i};");

				if (stage.Repeated && recovery is not null)
					file.Line($"ordinal{i}++;");

				file.Line($"start = end{i};");
			}
		}

		file.Line();

		EmitOverLines(
			file,
			$"global::System.Collections.Generic.IEnumerable<{element}>",
			publication.MethodName,
			publication.Rule.Name);
	}

	static string Comment(Stage stage) =>
		stage.Rule is { } rule
			? (stage.Repeated ? "every " : "") + rule.Name
			: stage.Node.ToString();

	static string Named(Stage stage) => stage.Rule?.Name ?? stage.Node.ToString();

	/// <summary>
	/// What a streamed parse does with an element it could not read (§8.2, §8.3).
	/// </summary>
	/// <remarks>
	/// The same two answers as over a string, reached the same way: with a <c>=&gt;</c> the
	/// rejection takes its place in the sequence, and without one it is dropped and told to
	/// the hook. The names are supplied from the window rather than from a span, because
	/// only the window knows how far into the whole input it is — a line number counted
	/// inside the buffer would restart every time the buffer moved.
	/// </remarks>
	static void EmitStreamedRejection(
		Writer file, RecognitionGraph graph, Publication publication, Recovery recovery,
		string factory, int stage, string element)
	{
		string Supplied(string name) => name switch
		{
			"parserText"     => "window.Text(from, to - from)",
			"parserPosition" => "window.Offset + from",
			"parserOrdinal"  => $"ordinal{stage}",
			"parserLine"     => "window.LineAt(from)",
			"parserColumn"   => "window.ColumnAt(from)",
			"parserSpan"     => "new global::DotGram.SourceSpan((int)(window.Offset + from), to - from)",
			"parserMessage"  => $"\"Input does not match '{element}' at \" + " +
				$"(window.Offset + failure{stage}.Reach).ToString(" +
				"global::System.Globalization.CultureInfo.InvariantCulture) + \".\"",
			_                => "default",
		};

		if (recovery.Factory is null)
		{
			file.Line(
				$"{RecoveredMethod}(\"{element}\", {Supplied("parserText")}, " +
				$"{Supplied("parserPosition")}, {Supplied("parserLine")}, " +
				$"{Supplied("parserColumn")}, ordinal{stage}, {Supplied("parserMessage")});");
		}
		else
		{
			var arguments = new List<string>();

			foreach (var name in recovery.Asks)
				arguments.Add(Supplied(name));

			file.Line($"yield return {factory}({string.Join(", ", arguments)});");
		}

		file.Line($"ordinal{stage}++;");
	}

	/// <summary>
	/// One part of a streamed <c>parse</c>: what to recognize, and what becomes of it.
	/// </summary>
	/// <param name="Rule">The rule to call, or null for a part that yields nothing.</param>
	/// <param name="Repeated">Whether it is read until it stops matching.</param>
	/// <param name="Node">What it came from, for the comment above it.</param>
	sealed record Stage(RuleSymbol? Rule, bool Repeated, Node Node);

	/// <summary>
	/// A published rule broken into the parts a streamed parse reads one at a time.
	/// </summary>
	/// <remarks>
	/// <para>
	/// Only the operands of the rule itself, and only ones that are calls: what a stage
	/// hands over has to be a whole value of a rule, because that is the unit the parse
	/// commits to when it yields. Anything else in the sequence — <c>eof</c>, a literal
	/// separator, <c>Trivia</c> — is recognized and contributes nothing, which is exactly
	/// what §4.1 case 2 already says of it.
	/// </para>
	/// <para>
	/// Null when the rule is not that shape. There is no attempt to be clever here: a
	/// grammar this cannot decompose gets the reason and no overload, which is better than
	/// a driver that quietly reads something else.
	/// </para>
	/// </remarks>
	static IReadOnlyList<Stage>? StagesOf(RecognitionGraph graph, RuleSymbol rule)
	{
		var body = graph.Bodies[rule];

		if (body is Node.Construct(var built, _))
			body = built;

		var parts  = body is Node.Sequence(var sequence) ? sequence : [body];
		var stages = new List<Stage>(parts.Count);

		foreach (var part in parts)
			switch (part)
			{
				case Node.Capture(_, Node.Call(var called, _)):
					stages.Add(new Stage(called, Repeated: false, part));
					break;

				case Node.Repeat(Node.Capture(_, Node.Call(var called, _)), _, _):
					stages.Add(new Stage(called, Repeated: true, part));
					break;

				// Consumes and yields nothing. A capture of something that is not a call
				// would be a value with no rule to recognize it on its own, so it is not one
				// of these — it is what makes the rule undecomposable.
				case Node.Capture:
					return null;

				default:
					stages.Add(new Stage(null, Repeated: false, part));
					break;
			}

		return stages;
	}

	/// <summary>Whether anything in this grammar reads through a window.</summary>
	static bool Streaming(RecognitionGraph graph)
	{
		foreach (var publication in graph.Publications)
			if (Streams(graph, publication))
				return true;

		return false;
	}

	static bool Streams(RecognitionGraph graph, Publication publication) =>
		publication.Kind == PublishKind.Find
			? Retention.ExtentOf(graph).TryGetValue(publication.Rule, out var extent) &&
				extent != LineExtent.Beyond
			: Retention.StreamedParse(graph, publication.Rule) is null;

	/// <summary>
	/// The type a rule's captures are built into: a constructor and a get-only property
	/// per capture, and nothing else.
	/// </summary>
	/// <remarks>
	/// <c>public</c>, unlike the support types of §6.1 — those are shared between
	/// assemblies and so have a version to skew, while this one is generated from the
	/// grammar it belongs to, in the assembly that uses it. That is what lets a published
	/// method hand it back.
	/// </remarks>
	static void EmitResultType(Writer file, RecognitionGraph graph, ResultTypes results, RuleSymbol rule)
	{
		var name    = results.NameOf(rule)!;
		var members = graph.Results[rule];

		string Type(ResultMember member) =>
			results.ValueOf(member.Rule) + (member.IsSequence ? "[]" : member.IsOptional ? "?" : "");

		file.Line($"/// <summary>What the rule <c>{rule.Name}</c> recognized.</summary>");

		using (file.Block($"public sealed class {name}"))
		{
			var parameters = members.Select(member => $"{Type(member)} {ResultTypes.ParameterOf(member)}");

			using (file.Block($"public {name}({string.Join(", ", parameters)})"))
				foreach (var member in members)
					file.Line($"{ResultTypes.PropertyOf(member, name)} = {ResultTypes.ParameterOf(member)};");

			foreach (var member in members)
			{
				file.Line();
				file.Line($"/// <summary>The <c>{member.Name}</c> capture.</summary>");
				file.Line($"public {Type(member)} {ResultTypes.PropertyOf(member, name)} {{ get; }}");
			}
		}
	}

	/// <summary>What a rule's machine builds, or null when its value is the text.</summary>
	static Machine.Built? BuiltBy(RecognitionGraph graph, ResultTypes results, RuleSymbol rule) =>
		results.QualifiedOf(rule) is not { } type
			? null
			: new Machine.Built(
				type,
				graph.Results[rule],
				LayoutOf(graph, results, rule),
				FactoriesOf(graph, results, rule));

	/// <summary>
	/// The methods a rule's <c>=&gt;</c> expressions become: the C# they named, with the
	/// captures as parameters.
	/// </summary>
	/// <remarks>
	/// <para>
	/// A method rather than an expression written where the value is assigned, and that
	/// is what makes the capture names usable at all — inside the machine they would have
	/// to dodge every local it has, and a capture called <c>p</c> or <c>state</c> would
	/// collide with the recognizer itself. Here they are parameters, in a scope of their
	/// own, named exactly as the grammar named them.
	/// </para>
	/// <para>
	/// One per alternative that carries a <c>=&gt;</c>, in the order they are written,
	/// which is the order the machine numbers them by.
	/// </para>
	/// </remarks>
	static IReadOnlyList<Machine.Factory> FactoriesOf(
		RecognitionGraph graph, ResultTypes results, RuleSymbol rule)
	{
		var name   = "Construct_" + IdentifierOf(rule);
		var fold   = graph.Folds.TryGetValue(rule, out var found0) ? found0 : null;
		var layout = LayoutOf(graph, results, rule);
		var found  = new List<Machine.Factory>();

		foreach (var node in Fold.Of(graph.Bodies[rule], fold))
		{
			if (node is not Node.Construct)
				continue;

			var from    = layout.Before(node);
			var to      = layout.After(node);
			var visible = new List<ResultMember>();

			// Only what this alternative could have captured, and optional only where this
			// alternative may skip it. A sibling's captures are neither its business nor
			// ever written when it is the one that matched.
			foreach (var member in graph.Results[rule])
			{
				var mine = new List<int>();

				foreach (var slot in member.Slots)
					if (slot >= from && slot < to)
						mine.Add(slot);

				if (mine.Count > 0)
					visible.Add(member with
					{
						Slots      = mine,
						IsOptional = !GrammarNormalizer.Writes(node, member.Name),
					});
			}

			found.Add(new Machine.Factory(
				node,
				found.Count == 0 ? name : name + "_" + found.Count,
				visible,
				fold is not null && fold.Accumulators.TryGetValue(node, out var accumulator)
					? accumulator
					: null,
				graph.Fallible.Contains(node)));
		}

		return found;
	}

	/// <summary>Where a rule's captures are, with its fold loop known for what it is.</summary>
	static CaptureLayout LayoutOf(RecognitionGraph graph, ResultTypes results, RuleSymbol rule) =>
		CaptureLayout.Of(
			graph.Bodies[rule],
			other => results.QualifiedOf(other) is not null,
			graph.Folds.TryGetValue(rule, out var fold) ? fold.Loop : null);

	static void EmitFactory(
		Writer file, RecognitionGraph graph, RuleSymbol rule, Machine.Factory factory, ResultTypes results)
	{
		var parameters = new List<string> { "string parserText" };

		// A fold step is handed the value built so far under the name it captured the
		// rule itself by (§4.3). It is not a capture any more — the rewrite took the call
		// away — so it is written in here rather than found among the members.
		if (factory.Accumulator is { Length: > 0 } accumulator)
			parameters.Add($"{graph.Types[rule]} {accumulator}");

		foreach (var member in factory.Members)
			if (member.Name != "parserText" && member.Name != factory.Accumulator)
				parameters.Add(
					results.ValueOf(member.Rule) +

					// A fold step is applied once per iteration and is handed that
					// iteration's captures, so what collects for the rule arrives here as
					// one of what it collected.
					(member.IsSequence && factory.Accumulator is null ? "[]" :
						member.IsOptional ? "?" : "") +

					" " + ResultTypes.ParameterOf(member));

		// §8.1: a transformation that may refuse hands its value back through an `out` and
		// says whether there is one, so the factory does too. The `out` argument is already
		// in the text — written where the call was still a shape.
		if (graph.Fallible.Contains(factory.Of))
		{
			parameters.Add($"out {graph.Types[rule]} value");

			file.Line($"/// <summary>What <c>{rule.Name}</c> builds its value with, or refuses to (§8.1).</summary>");
			file.Line($"static bool {factory.Method}({string.Join(", ", parameters)}) =>");
			file.Line("\t" + ((Node.Construct)factory.Of).Text + ";");

			return;
		}

		// §4.1 case 2: the grammar wrote no expression, so there is none to write out. What
		// the rule is made of is its operands, in order, and the body says so — a body and
		// not an expression because a repetition contributes an unknown number of elements
		// and an optional operand contributes none, so the length is not known in advance.
		if (((Node.Construct)factory.Of).Text == GrammarNormalizer.SequenceMarker)
		{
			var element = graph.Types[rule].Substring(0, graph.Types[rule].Length - "[]".Length);

			file.Line($"/// <summary>Everything <c>{rule.Name}</c> is made of, in order (§4.1 case 2).</summary>");

			using (file.Block($"static {graph.Types[rule]} {factory.Method}({string.Join(", ", parameters)})"))
			{
				file.Line($"var items = new global::System.Collections.Generic.List<{element}>();");
				file.Line();

				foreach (var member in factory.Members)
				{
					var value = ResultTypes.ParameterOf(member);

					// Null where the alternative that captured it was not the one that
					// matched, and an empty run is an empty array that adds nothing.
					if (member.IsSequence || member.IsOptional)
					{
						file.Line($"if ({value} != null)");
						file.Then($"items.{(member.IsSequence ? "AddRange" : "Add")}({value});");
					}
					else
					{
						file.Line($"items.Add({value});");
					}
				}

				file.Line();
				file.Line("return items.ToArray();");
			}

			return;
		}

		file.Line($"/// <summary>What <c>{rule.Name}</c> builds its value with (docs/syntax.md §7.3).</summary>");
		file.Line($"static {graph.Types[rule]} {factory.Method}({string.Join(", ", parameters)}) =>");
		file.Line("\t" + ((Node.Construct)factory.Of).Text + ";");
	}

	/// <summary>
	/// The repetition of a rule that was marked <c>recover</c>, the slot its elements
	/// collect into, and what it was told (§8.2).
	/// </summary>
	static (Node Repetition, Recovery Recovery, int Slot)? RecoveryIn(
		RecognitionGraph graph, ResultTypes results, RuleSymbol rule)
	{
		if (graph.Recoveries.Count == 0)
			return null;

		var layout = LayoutOf(graph, results, rule);

		return Find(graph.Bodies[rule], -1);

		// The capture is where a recovered element goes: the same sequence its successful
		// siblings collect into. It may be either side of the quantifier — `rows: Row*` is
		// `(rows: Row)*`, because a capture binds tighter (§10) — so both are looked at.
		(Node, Recovery, int)? Find(Node node, int slot)
		{
			if (node is Node.Repeat(var repeated, _, _) && graph.Recoveries.TryGetValue(node, out var recovery))
				return (node, recovery, slot >= 0 ? slot : repeated is Node.Capture ? layout.SlotOf(repeated) : -1);

			if (node is Node.Capture(_, var captured))
				return Find(captured, layout.SlotOf(node));

			foreach (var child in Children(node))
				if (Find(child, -1) is { } found)
					return found;

			return null;
		}
	}

	static IEnumerable<Node> Children(Node node) => node switch
	{
		Node.Sequence(var nodes)     => nodes,
		Node.Choice(var nodes)       => nodes,
		Node.Repeat(var body, _, _)  => [body],
		Node.Construct(var body, _)  => [body],
		_                            => [],
	};

	/// <summary>
	/// What a broken element becomes: the C# the <c>recover</c> named, with the extent it
	/// covered and where in the sequence it was.
	/// </summary>
	static void EmitRecoveryFactory(
		Writer file, ResultTypes results, RuleSymbol rule, string owner, Recovery recovery,
		RecognitionGraph graph, int slot)
	{
		var element    = LayoutOf(graph, results, rule).Slots[slot].Rule;
		var parameters = new List<string>();

		foreach (var name in recovery.Asks)
			parameters.Add(TypeOfSupplied(name) + " " + name);

		file.Line($"/// <summary>What <c>{rule.Name}</c> makes of an element it could not read.</summary>");
		file.Line(
			$"static {results.ValueOf(element)} {owner}_Recover({string.Join(", ", parameters)}) =>");
		file.Line("\t" + recovery.Factory + ";");
		file.Line();
	}

	/// <summary>Whether any <c>recover</c> in this grammar asked where its element was.</summary>
	/// <remarks>
	/// A <c>recover</c> without a <c>=&gt;</c> always asks: the hook it reports on takes
	/// the line and the column whether or not anybody implements it.
	/// </remarks>
	static bool Locating(RecognitionGraph graph)
	{
		foreach (var recovery in graph.Recoveries.Values)
		{
			if (recovery.Factory is null)
				return true;

			var asked = recovery.Asks;

			if (asked.Contains("parserLine") || asked.Contains("parserColumn"))
				return true;
		}

		return false;
	}

	/// <summary>
	/// Whether recovery in this grammar ever has a refused value to tell from a shape that
	/// did not match (§8.1).
	/// </summary>
	static bool Refusing(RecognitionGraph graph) =>
		graph.Recoveries.Count > 0 && graph.Fallible.Count > 0;

	/// <summary>Whether any <c>recover</c> in this grammar reports out of band (§8.3).</summary>
	static bool Reporting(RecognitionGraph graph)
	{
		foreach (var recovery in graph.Recoveries.Values)
			if (recovery.Factory is null)
				return true;

		return false;
	}

	/// <summary>
	/// The C# type of a name §8.2 supplies to a failure factory.
	/// </summary>
	/// <remarks>
	/// <c>position</c> is a <c>long</c> and everything else counting is an <c>int</c>,
	/// which is the frozen rule: an absolute offset is into the input, and an input may be
	/// a file larger than an <c>int</c> can index, while an extent is into a buffer and a
	/// buffer never is. A line number and an ordinal are counts of things in that file
	/// rather than positions in it, and nothing counts two billion lines.
	/// </remarks>
	static string TypeOfSupplied(string name) => name switch
	{
		"parserText" or "parserMessage" => "string",
		"parserSpan"                    => "global::DotGram.SourceSpan",
		"parserPosition"                => "long",
		_                               => "int",
	};

	/// <summary>One rule, and whether it needed the shared stack helper.</summary>
	static bool EmitRule(Writer file, RecognitionGraph graph, ResultTypes results, RuleSymbol rule)
	{
		var machine = new Machine(MethodOf(rule), results, BuiltBy(graph, results, rule))
		{
			Reaches    = graph.Recoveries.Count > 0,
			Refuses    = Refusing(graph),
			TakesPower = graph.Climbing.ContainsKey(rule),
		};

		machine.Climbs(
			graph.Climbing,
			graph.Powers,
			graph.Climbing.TryGetValue(rule, out var levels) ? levels : new Dictionary<Node, int>());

		if (RecoveryIn(graph, results, rule) is var (repetition, recovery, slot))
		{
			machine.Recovers(repetition, recovery, slot, MethodOf(rule) + "_Recover");

			if (recovery.Factory is not null && slot >= 0)
				EmitRecoveryFactory(file, results, rule, MethodOf(rule), recovery, graph, slot);
		}

		var entry   = machine.Compile(graph.Bodies[rule], Machine.Accept);
		var text    = machine.Render(entry, $"{rule.Name} = {graph.Bodies[rule]}");

		foreach (var extra in machine.Extra)
		{
			file.Write(extra);
			file.Line();
		}

		file.Write(text);

		return machine.UsesStack || machine.Extra.Count > 0;
	}

	internal static string MethodOf(RuleSymbol rule) => "Recognize_" + IdentifierOf(rule);

	/// <summary>
	/// A rule's name as one C# identifier, unique across the grammar.
	/// </summary>
	/// <remarks>
	/// The short name is not unique and is not meant to be — shadowing is what a scope is
	/// for, so a grammar with a <c>Trivia</c> per scope is the ordinary case rather than a
	/// clash. The scopes a rule is declared in are prefixed to tell them apart, named
	/// rather than numbered so that a reader of the generated code can still see which
	/// rule a method came from. The standard library's scope is not an identifier and is
	/// left off: its names are fixed, and a grammar that shadows one of them takes the
	/// name with it.
	/// </remarks>
	internal static string IdentifierOf(RuleSymbol rule)
	{
		var name = rule.Name;

		for (var scope = rule.Scope; scope is { Name.Length: > 0 }; scope = scope.Parent)
			if (IsIdentifier(scope.Name))
				name = scope.Name + "_" + name;

		return name;
	}

	static bool IsIdentifier(string name)
	{
		foreach (var c in name)
			if (!char.IsLetterOrDigit(c) && c != '_')
				return false;

		return true;
	}

	/// <summary>The recognizer that also insists the input ended — what `parse` calls.</summary>
	static string WholeOf(RuleSymbol rule) => MethodOf(rule) + "_Whole";

	/// <summary>
	/// End of input: the complement of everything, not present. The same node `eof`
	/// lowers to, built here rather than looked up so that a grammar which never
	/// mentions `eof` still gets one.
	/// </summary>
	static Node EndOfInput =>
		new Node.Lookahead(IsPositive: false, new Node.Element(IsNegated: true, [], [], []));

	/// <summary>What a publication answers with. The name a rule may not take.</summary>
	internal const string MatchType = "Match";

	/// <summary>What a streamed parse reads through. The name a rule may not take.</summary>
	internal const string WindowType = "Window";

	/// <summary>
	/// How much of a reader a window holds before it has to grow.
	/// </summary>
	/// <remarks>
	/// A page. Small enough that a short input costs one allocation of no consequence,
	/// large enough that a line-oriented feed never grows it — and where an element is
	/// longer than this, growing is what the retention analysis promised would be
	/// bounded, not what it promised would not happen.
	/// </remarks>
	const int WindowSize = 4096;

	/// <summary>
	/// A reader read through a buffer that is reused, and the reason streaming works at
	/// all.
	/// </summary>
	/// <remarks>
	/// <para>
	/// §6.3 fixes what has to be held: a call reaches back not at all and a rule reaches
	/// back exactly as far as it has consumed, so what the window must keep is the extent
	/// of the outermost rule still in progress. Everything before where the parse is now
	/// can be dropped, and this drops it — by moving what is left to the front of the same
	/// buffer, so a feed of a million records reads through one array.
	/// </para>
	/// <para>
	/// It is not a line reader, deliberately. The retention analysis measures in lines
	/// because that is what bounds a feed, but nothing here knows what a line is: two
	/// records may share one, one record may span three, and a grammar with no line
	/// terminators anywhere streams exactly as well. What the window answers is "how much
	/// can still be seen", which is the only question the machine asks of it.
	/// </para>
	/// <para>
	/// Growing rather than failing when an element does not fit: the analysis has already
	/// refused the grammars whose elements are unbounded (§6.3), so a grow here is a long
	/// record rather than a runaway.
	/// </para>
	/// </remarks>
	/// <summary>What a sequence of lines is read through. The name a rule may not take.</summary>
	internal const string LinesType = "Lines";

	/// <summary>
	/// A sequence of lines, read as though it were a file.
	/// </summary>
	/// <remarks>
	/// <para>
	/// §6.3 lists <c>IEnumerable&lt;string&gt;</c> beside <c>TextReader</c>, and this is
	/// the whole of the difference between them: a reader carries its terminators and a
	/// sequence of lines has had them taken off. So they are put back, as <c>\n</c>, and
	/// everything downstream is the reader case unchanged.
	/// </para>
	/// <para>
	/// Which terminator is a decision and not a detail. <c>\n</c> because a grammar's
	/// <c>eol</c> matches it, because it is what the lines came from more often than not,
	/// and because the alternative — putting back what was taken off — is not knowable:
	/// the sequence does not say, and <c>File.ReadLines</c> would not tell it.
	/// </para>
	/// </remarks>
	internal const string LinesClass = """
		/// <summary>A sequence of lines, read as though it were a file.</summary>
		sealed class Lines : global::System.IO.TextReader
		{
			private readonly global::System.Collections.Generic.IEnumerator<string> _lines;

			private string _line = "";
			private int    _at;
			private bool   _ended;

			public Lines(global::System.Collections.Generic.IEnumerable<string> lines)
			{
				_lines = lines.GetEnumerator();
			}

			public override int Read(char[] buffer, int index, int count)
			{
				var written = 0;

				while (written < count)
				{
					if (_at >= _line.Length && !Next())
						break;

					var taking = global::System.Math.Min(count - written, _line.Length - _at);

					_line.CopyTo(_at, buffer, index + written, taking);

					_at     += taking;
					written += taking;
				}

				return written;
			}

			/// <summary>
			/// The next line, with the terminator the sequence does not carry put back.
			/// </summary>
			private bool Next()
			{
				if (_ended)
					return false;

				if (!_lines.MoveNext())
				{
					_ended = true;

					return false;
				}

				_line = _lines.Current + "\n";
				_at    = 0;

				return true;
			}

			protected override void Dispose(bool disposing)
			{
				if (disposing)
					_lines.Dispose();

				base.Dispose(disposing);
			}
		}
		""";

	internal const string WindowClass = """
		/// <summary>A reader, read through a buffer that is reused.</summary>
		sealed class Window
		{
			private readonly global::System.IO.TextReader _input;

			private char[] _buffer;
			private int    _filled;
			private long   _offset;
			private bool   _ended;

			/// <summary>Line terminators dropped with what the window no longer holds.</summary>
			private int _lines;

			/// <summary>Where the last of them was, or -1 when none has been dropped.</summary>
			private long _break = -1;

			public Window(global::System.IO.TextReader input, int capacity)
			{
				_input  = input;
				_buffer = new char[capacity];
			}

			/// <summary>How much of the input the window is holding.</summary>
			public int Length
			{
				get { return _filled; }
			}

			/// <summary>Whether the reader has been read to its end.</summary>
			public bool Ended
			{
				get { return _ended; }
			}

			/// <summary>Where the window begins in the whole input.</summary>
			public long Offset
			{
				get { return _offset; }
			}

			/// <summary>
			/// What the window holds.
			/// </summary>
			/// <remarks>
			/// Called where it is passed and never kept in a local: a span cannot live in
			/// an iterator's state, and every published streaming method is an iterator.
			/// </remarks>
			public global::System.ReadOnlySpan<char> Span()
			{
				return new global::System.ReadOnlySpan<char>(_buffer, 0, _filled);
			}

			/// <summary>A stretch of the window, as a string.</summary>
			public string Text(int from, int length)
			{
				return new string(_buffer, from, length);
			}

			/// <summary>
			/// Which line of the whole input a position in the window is on, from 1.
			/// </summary>
			/// <remarks>
			/// The window's own contents plus what was dropped before it. Counting only
			/// what is held would restart the numbering every time the buffer moved.
			/// </remarks>
			public int LineAt(int position)
			{
				var line = _lines + 1;

				for (var at = 0; at < position; at++)
					if (_buffer[at] == '\n')
						line++;

				return line;
			}

			/// <summary>How far into its line a position is, from 1.</summary>
			public int ColumnAt(int position)
			{
				var start = -1;

				for (var at = 0; at < position; at++)
					if (_buffer[at] == '\n')
						start = at;

				// The line began before the window did, so the length of what is held is
				// only part of the answer and the rest is where the last dropped
				// terminator was.
				return start < 0
					? (int)(_offset + position - _break)
					: position - start;
			}

			/// <summary>
			/// Reads more of the input, dropping what is before <paramref name="from"/> to
			/// make room for it and moving <paramref name="from"/> with what is kept.
			/// </summary>
			/// <returns>Whether anything new arrived.</returns>
			public bool Extend(ref int from)
			{
				if (_ended)
					return false;

				if (_filled == _buffer.Length)
				{
					if (from > 0)
					{
						// What is about to be dropped is where a line number comes from, so
						// it is counted on the way out. Without this a position past the
						// first window would be reported as a line near the top of the file.
						for (var at = 0; at < from; at++)
							if (_buffer[at] == '\n')
							{
								_lines++;
								_break = _offset + at;
							}

						global::System.Array.Copy(_buffer, from, _buffer, 0, _filled - from);

						_filled -= from;
						_offset += from;
						from     = 0;
					}
					else
					{
						var grown = new char[_buffer.Length * 2];

						global::System.Array.Copy(_buffer, 0, grown, 0, _filled);

						_buffer = grown;
					}
				}

				var read = _input.Read(_buffer, _filled, _buffer.Length - _filled);

				if (read <= 0)
				{
					_ended = true;

					return false;
				}

				_filled += read;

				return true;
			}
		}
		""";

	/// <summary>
	/// One answer from a publication: what was recognized, or why nothing was.
	/// </summary>
	/// <remarks>
	/// <para>
	/// Unconstrained, because a rule may declare itself <c>: @int</c>. <c>Value</c> is
	/// therefore <c>T</c> and not <c>T?</c> — an unconstrained <c>T?</c> needs a language
	/// version this generator may not assume — and <c>IsSuccess</c> is what says whether
	/// there is one. On a failure it is <c>default</c>.
	/// </para>
	/// <para>
	/// One type for the whole grammar rather than one per rule: only the value differs,
	/// and a per-rule copy of the same four members would be noise in every generated
	/// file.
	/// </para>
	/// </remarks>
	internal const string MatchStruct = """
		/// <summary>What a publication answers with: the value, or why there is none.</summary>
		public readonly struct Match<T>
		{
			private Match(bool isSuccess, T value, string? error, long position, int length)
			{
				IsSuccess = isSuccess;
				Value     = value;
				Error     = error;
				Position  = position;
				Length    = length;
			}

			/// <summary>Whether there is a value.</summary>
			public bool IsSuccess { get; }

			/// <summary>What was recognized. Meaningless unless <c>IsSuccess</c>.</summary>
			public T Value { get; }

			/// <summary>Why nothing was recognized, or null.</summary>
			public string? Error { get; }

			/// <summary>
			/// Where the match began, or how far the input could be followed before it
			/// failed. An offset into the whole input, so a <c>long</c>: an input may be a
			/// file larger than an <c>int</c> can index (docs/syntax.md §6.3).
			/// </summary>
			public long Position { get; }

			/// <summary>
			/// How much was matched, in input items, and zero when nothing was. An extent
			/// into a buffer rather than an offset into the input, so an <c>int</c>.
			/// </summary>
			public int Length { get; }

			internal static Match<T> Success(T value, long position, int length)
			{
				return new Match<T>(true, value, null, position, length);
			}

			internal static Match<T> Failed(string error, long position)
			{
				return new Match<T>(false, default!, error, position, 0);
			}
		}
		""";

	/// <summary>
	/// What every recognizer carries so that a failure can be described.
	/// </summary>
	/// <remarks>
	/// The name a rule may not take: <see cref="ResultTypes"/> renames its own type
	/// instead if a grammar declares a rule called this.
	/// </remarks>
	internal const string FailureType = "Failure";

	/// <summary>
	/// The record of the best failure a match saw, threaded through every recognizer.
	/// </summary>
	/// <remarks>
	/// A struct passed by <c>ref</c> rather than more <c>out</c> parameters, and that is
	/// the point of it: what a failure has to say is going to grow — the set of what was
	/// expected there, an outcome that tells a malformed record from no record at all
	/// (docs/syntax.md §8.1) — and each of those would otherwise be another parameter on
	/// every recognizer and another edit at every call site.
	/// </remarks>
	internal static string FailureStructWith(bool reach, bool refused = false) =>
		Lines.Normalize(FailureStruct)
			.Replace(
				"\t{{reach}}" + Lines.Ending,
				reach ? Lines.Normalize(ReachField) + Lines.Ending : "")
			.Replace(
				"\t{{refused}}" + Lines.Ending,
				refused ? Lines.Normalize(RefusedField) + Lines.Ending : "");

	const string FailureStruct = """
		/// <summary>Where a match got before it gave up, and why.</summary>
		struct Failure
		{
			/// <summary>
			/// The furthest position the input was followed to. Zero on a match that
			/// succeeded without ever backtracking, and meaningless unless one failed.
			/// </summary>
			public int Position;
			{{reach}}
			{{refused}}
		}
		""";

	/// <summary>
	/// The field a recovering grammar needs beside <c>Position</c>, and one that a grammar
	/// not using recovery does not carry.
	/// </summary>
	/// <remarks>
	/// <c>Position</c> is the whole parse's furthest and something further along may
	/// already have raised it, so it cannot say whether <b>this</b> element began. This one
	/// is reset where each element begins, which is exactly the question §8.2 asks.
