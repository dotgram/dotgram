/// <summary>Indent-aware output. One per generated function, so nothing interleaves.</summary>
sealed class Writer(int depth)
{
	readonly StringBuilder _text = new();

	int _depth = depth;

	/// <summary>How far in the next line will be written — what a nested writer starts at.</summary>
	public int Depth => _depth;

	public void Line(string text = "")
	{
		if (text.Length == 0)
			_text.EndLine();
		else
			_text.Append('\t', _depth).AppendEndingWith(text);
	}

	/// <summary>A single indented line — the body of an <c>if</c> without braces.</summary>
	public void Then(string text)
	{
		_depth++;
		Line(text);
		_depth--;
	}

	public IDisposable Block(string header)
	{
		Line(header);
		Line("{");
		_depth++;

		return new Closer(this);
	}

	/// <summary>Indents what follows, without braces around it — a switch section.</summary>
	public IDisposable Indent()
	{
		_depth++;

		return new Outdenter(this);
	}

	public void Append(Writer other) => _text.Append(other._text);

	/// <summary>
	/// Writes text that is already laid out, each line at the current depth.
	/// </summary>
	/// <remarks>
	/// The endings are normalized first, and that is not tidiness. What arrives here is a
	/// raw string literal, whose content is whatever the file it was typed in was saved
	/// with — so a generator whose own source went from CRLF to LF would silently start
	/// emitting every one of these blocks as a single unsplit line, indented once and
	/// flattened after that. Generated code must not depend on how the generator was
	/// saved.
	/// </remarks>
	public void Write(string text)
	{
		var written = new Writer(0);

		written._text.Append(Lines.Normalize(text));

		// AppendIndented reads the text as lines, each closed by an ending. Text that
		// does not end with one — a raw string literal, say — would lose its last line.
		if (!text.EndsWith(Lines.Ending, StringComparison.Ordinal))
			written._text.Append(Lines.Ending);

		AppendIndented(written, 0);
	}

	/// <summary>Appends another writer's text, shifted in to this one's depth.</summary>
	public void AppendIndented(Writer other, int extra = 1)
	{
		var lines = other._text.ToString().Split([Lines.Ending], StringSplitOptions.None);

		// The text ends with an ending, so the split leaves a final empty piece that is
		// not a line at all.
		for (var i = 0; i < lines.Length - 1; i++)
			if (lines[i].Length > 0)
				_text.Append('\t', _depth + extra).AppendEndingWith(lines[i]);
			else
				_text.EndLine();
	}

	public override string ToString() => _text.ToString();

	sealed class Closer(Writer writer) : IDisposable
	{
		public void Dispose()
		{
			writer._depth--;
			writer.Line("}");
		}
	}

	sealed class Outdenter(Writer writer) : IDisposable
	{
		public void Dispose() => writer._depth--;
	}
}

/// <summary>
/// Turns a recognition graph into C#.
/// </summary>
/// <remarks>
/// <para>
/// One method per rule, and inside it one static local function per node. Every one of
/// them has the same shape — take the input and a position, return the new position or
/// -1 — so composing them is just calling them, and there is nothing to allocate,
/// nothing virtual, and no closure. Static local functions specifically, because a
/// closure cannot hold a <c>ReadOnlySpan</c>.
/// </para>
/// <para>
/// This is the fast path over the frozen subset of docs/implementation.md §11:
/// sequence, ordered choice, quantifiers, element sets, literals, rule calls. No
/// trivia, no result construction, no recovery yet — a rule's value is the text it
/// matched.
/// </para>
/// </remarks>
public static class CSharpEmitter
{
	/// <param name="graph">The normalized grammar.</param>
	/// <param name="className">
	/// The partial class the generated members go into. A nested host is named by its
	/// chain — <c>Outer.Inner</c> — and written back out nested.
	/// </param>
	/// <param name="namespace">Its namespace, or null for the global one.</param>
	public static string Emit(RecognitionGraph graph, string className, string? @namespace = null)
	{
		if (graph is null)
			throw new ArgumentNullException(nameof(graph));

		var file    = new Writer(0);
		var scope   = new Stack<IDisposable>();
		var results = new ResultTypes(graph, className, @namespace);

		file.Line("// <auto-generated/>");
		file.Line("#nullable enable");
		file.Line();

		// A block namespace rather than a file-scoped one: the consumer's language
		// version is unknown (.claude/rules/emitted-code.md).
		if (@namespace is not null)
			scope.Push(file.Block($"namespace {@namespace}"));

		// The grammar's own `@using` directives and no others. Everything this file
		// generates is written with `global::`; these are here for the C# the grammar
		// supplied, which was written expecting them (§1).
		if (graph.CSharpImports.Count > 0)
		{
			foreach (var import in graph.CSharpImports)
				file.Line($"using {import};");

			file.Line();
		}

		foreach (var name in className.Split('.'))
			scope.Push(file.Block($"partial class {name}"));

		foreach (var publication in graph.Publications)
		{
			EmitPublication(file, publication, results);
			file.Line();
		}

		foreach (var rule in results.Built)
		{
			EmitResultType(file, graph, results, rule);
			file.Line();
		}

		foreach (var rule in graph.Rules)
		{
			if (!graph.Types.ContainsKey(rule))
				continue;

			foreach (var factory in FactoriesOf(graph, results, rule))
			{
				EmitFactory(file, graph, rule, factory, results);
				file.Line();
			}
		}

		var needsStack = false;

		// `parse` demands the input end. Asking the rule and then checking would leave it
		// unable to go back for a longer match — the check has to be inside the machine,
		// where failing it is an ordinary failure and the stack still has somewhere to
		// resume. So the rule's body is compiled again, with end-of-input on the end.
		foreach (var publication in graph.Publications)
		{
			if (publication.Kind != PublishKind.Parse)
				continue;

			var whole = new Machine(
				WholeOf(publication.Rule), results, BuiltBy(graph, results, publication.Rule))
			{
				Reaches = graph.Recoveries.Count > 0,
			};

			// A rule that recovers recovers however it is entered. The whole-input machine is
			// the same body compiled a second time, so it is told the same thing — and calls
			// the one factory, which the rule's own machine emits.
			if (RecoveryIn(graph, results, publication.Rule) is var (repeats, recovers, into))
				whole.Recovers(repeats, recovers, into, MethodOf(publication.Rule) + "_Recover");

			// The two ends normalization cannot reach: it inserts Trivia between operands,
			// and a whole parse has an outside (§4.5).
			var body = graph.Trivia.TryGetValue(publication.Rule, out var trivia)
				? new Node.Sequence([trivia, graph.Bodies[publication.Rule], trivia, EndOfInput])
				: new Node.Sequence([graph.Bodies[publication.Rule], EndOfInput]);

			file.Write(whole.Render(
				whole.Compile(body, Machine.Accept),
				$"parse {publication.Rule.Name}: {graph.Bodies[publication.Rule]} & eof"));
			file.Line();

			foreach (var extra in whole.Extra)
			{
				file.Write(extra);
				file.Line();
			}

			needsStack = true;
		}

		foreach (var rule in graph.Rules)
		{
			needsStack |= EmitRule(file, graph, results, rule);
			file.Line();
		}

		if (graph.Publications.Count > 0)
		{
			file.Write(MatchStruct);
			file.Line();
		}

		if (graph.Rules.Count > 0)
		{
			file.Write(FailureStructWith(graph.Recoveries.Count > 0));
			file.Line();
		}

		if (Locating(graph))
		{
			file.Write(LocateHelper);
			file.Line();
		}

		if (needsStack)
			file.Write(GrowHelper);

		while (scope.Count > 0)
			scope.Pop().Dispose();

		return file.ToString();
	}

	/// <summary>
	/// One directive (docs/syntax.md §6). <c>parse</c> makes an asserting method and an
	/// asking one; <c>find</c> makes a sequence.
	/// </summary>
	/// <remarks>
	/// No <c>out</c> parameters anywhere: what a match has to say goes in
	/// <see cref="MatchType"/>, where the next thing it has to say is a field rather than
	/// another parameter on every signature.
	/// </remarks>
	static void EmitPublication(Writer file, Publication publication, ResultTypes results)
	{
		var method = publication.MethodName;
		var name   = publication.Rule.Name;
		var built  = results.QualifiedOf(publication.Rule);
		var value  = built ?? "string";
		var match  = $"{MatchType}<{value}>";

		// A rule that builds hands its value back through the recognizer; one that does
		// not leaves the extent it matched, and the text is cut from the input.
		var hands = built is null ? ", ref failure" : ", ref failure, out var recognized";

		string Recognized(string from, string to) =>
			built is null ? $"input.Substring({from}, {to})" : "recognized";

		if (publication.Kind == PublishKind.Find)
		{
			EmitFind(file, publication, method, name, value, match, hands, Recognized);

			return;
		}

		file.Line($"/// <summary>Parses the whole input as <c>{name}</c>.</summary>");
		file.Line("/// <exception cref=\"global::System.FormatException\">");
		file.Line($"/// The input is not <c>{name}</c>. <c>Try{method}</c> answers instead.");
		file.Line("/// </exception>");

		using (file.Block($"public static {value} {method}(string input)"))
		{
			file.Line($"var match = Try{method}(input);");
			file.Line();
			file.Line("if (match.IsSuccess)");
			file.Then("return match.Value;");
			file.Line();
			file.Line("throw new global::System.FormatException(match.Error + \" at \" + match.Position.ToString());");
		}

		file.Line();
		file.Line($"/// <summary>Parses the whole input as <c>{name}</c>, answering rather than throwing.</summary>");

		using (file.Block($"public static {match} Try{method}(string input)"))
		{
			// Fully qualified, and as a static call rather than an extension method:
			// the emitted file carries no usings at all (.claude/rules/emitted-code.md).
			file.Line("var text    = global::System.MemoryExtensions.AsSpan(input);");

			// Carried through every recognizer this call reaches, so that what comes back
			// is the furthest the input was followed and not merely "no".
			file.Line($"var failure = new {FailureType}();");
			file.Line();
			file.Line($"var end = {WholeOf(publication.Rule)}(text, 0{hands});");
			file.Line();
			file.Line("if (end < 0)");
			file.Then($"return {match}.Failed(\"Input does not match '{name}'.\", failure.Position);");
			file.Line();
			file.Line($"return {match}.Success({Recognized("0", "end")}, 0, end);");
		}
	}

	/// <summary>
	/// <c>find</c>: every occurrence, one at a time.
	/// </summary>
	/// <remarks>
	/// An iterator rather than an array, so that a document with a million occurrences
	/// costs one at a time — and so that "the first one" and "the ones that satisfy this"
	/// are LINQ's rather than three more directives. The span is made where it is passed
	/// and never held in a local, which is what lets this be an iterator at all.
	/// </remarks>
	static void EmitFind(
		Writer file, Publication publication, string method, string name,
		string value, string match, string hands, Func<string, string, string> recognized)
	{
		file.Line($"/// <summary>Every occurrence of <c>{name}</c>, in order, found as it is asked for.</summary>");

		using (file.Block(
			$"public static global::System.Collections.Generic.IEnumerable<{match}> {method}(string input)"))
		{
			using (file.Block("for (var start = 0; start <= input.Length; )"))
			{
				file.Line($"var failure = new {FailureType}();");
				file.Line();
				file.Line(
					$"var end = {MethodOf(publication.Rule)}(" +
					$"global::System.MemoryExtensions.AsSpan(input), start{hands});");
				file.Line();

				using (file.Block("if (end < 0)"))
				{
					file.Line("start++;");
					file.Line("continue;");
				}

				file.Line();
				file.Line($"yield return {match}.Success({recognized("start", "end - start")}, start, end - start);");
				file.Line();
				file.Line("// A rule that matches nothing would otherwise find it for ever.");
				file.Line("start = end > start ? end : start + 1;");
			}
		}
	}

	/// <summary>
	/// The type a rule's captures are built into: a constructor and a get-only property
	/// per capture, and nothing else.
	/// </summary>
	/// <remarks>
	/// <c>public</c>, unlike the support types of §6.1 — those are shared between
	/// assemblies and so have a version to skew, while this one is generated from the
	/// grammar it belongs to, in the assembly that uses it. That is what lets a published
	/// method hand it back.
	/// </remarks>
	static void EmitResultType(Writer file, RecognitionGraph graph, ResultTypes results, RuleSymbol rule)
	{
		var name    = results.NameOf(rule)!;
		var members = graph.Results[rule];

		string Type(ResultMember member) =>
			results.ValueOf(member.Rule) + (member.IsSequence ? "[]" : member.IsOptional ? "?" : "");

		file.Line($"/// <summary>What the rule <c>{rule.Name}</c> recognized.</summary>");

		using (file.Block($"public sealed class {name}"))
		{
			var parameters = members.Select(member => $"{Type(member)} {ResultTypes.ParameterOf(member)}");

			using (file.Block($"public {name}({string.Join(", ", parameters)})"))
				foreach (var member in members)
					file.Line($"{ResultTypes.PropertyOf(member, name)} = {ResultTypes.ParameterOf(member)};");

			foreach (var member in members)
			{
				file.Line();
				file.Line($"/// <summary>The <c>{member.Name}</c> capture.</summary>");
				file.Line($"public {Type(member)} {ResultTypes.PropertyOf(member, name)} {{ get; }}");
			}
		}
	}

	/// <summary>What a rule's machine builds, or null when its value is the text.</summary>
	static Machine.Built? BuiltBy(RecognitionGraph graph, ResultTypes results, RuleSymbol rule) =>
		results.QualifiedOf(rule) is not { } type
			? null
			: new Machine.Built(
				type,
				graph.Results[rule],
				LayoutOf(graph, results, rule),
				FactoriesOf(graph, results, rule));

	/// <summary>
	/// The methods a rule's <c>=&gt;</c> expressions become: the C# they named, with the
	/// captures as parameters.
	/// </summary>
	/// <remarks>
	/// <para>
	/// A method rather than an expression written where the value is assigned, and that
	/// is what makes the capture names usable at all — inside the machine they would have
	/// to dodge every local it has, and a capture called <c>p</c> or <c>state</c> would
	/// collide with the recognizer itself. Here they are parameters, in a scope of their
	/// own, named exactly as the grammar named them.
	/// </para>
	/// <para>
	/// One per alternative that carries a <c>=&gt;</c>, in the order they are written,
	/// which is the order the machine numbers them by.
	/// </para>
	/// </remarks>
	static IReadOnlyList<Machine.Factory> FactoriesOf(
		RecognitionGraph graph, ResultTypes results, RuleSymbol rule)
	{
		var name   = "Construct_" + IdentifierOf(rule);
		var fold   = graph.Folds.TryGetValue(rule, out var found0) ? found0 : null;
		var layout = LayoutOf(graph, results, rule);
		var found  = new List<Machine.Factory>();

		foreach (var node in Fold.Of(graph.Bodies[rule], fold))
		{
			if (node is not Node.Construct)
				continue;

			var from    = layout.Before(node);
			var to      = layout.After(node);
			var visible = new List<ResultMember>();

			// Only what this alternative could have captured, and optional only where this
			// alternative may skip it. A sibling's captures are neither its business nor
			// ever written when it is the one that matched.
			foreach (var member in graph.Results[rule])
			{
				var mine = new List<int>();

				foreach (var slot in member.Slots)
					if (slot >= from && slot < to)
						mine.Add(slot);

				if (mine.Count > 0)
					visible.Add(member with
					{
						Slots      = mine,
						IsOptional = !GrammarNormalizer.Writes(node, member.Name),
					});
			}

			found.Add(new Machine.Factory(
				node,
				found.Count == 0 ? name : name + "_" + found.Count,
				visible,
				fold is not null && fold.Accumulators.TryGetValue(node, out var accumulator)
					? accumulator
					: null));
		}

		return found;
	}

	/// <summary>Where a rule's captures are, with its fold loop known for what it is.</summary>
	static CaptureLayout LayoutOf(RecognitionGraph graph, ResultTypes results, RuleSymbol rule) =>
		CaptureLayout.Of(
			graph.Bodies[rule],
			other => results.QualifiedOf(other) is not null,
			graph.Folds.TryGetValue(rule, out var fold) ? fold.Loop : null);

	static void EmitFactory(
		Writer file, RecognitionGraph graph, RuleSymbol rule, Machine.Factory factory, ResultTypes results)
	{
		var parameters = new List<string> { "string text" };

		// A fold step is handed the value built so far under the name it captured the
		// rule itself by (§4.3). It is not a capture any more — the rewrite took the call
		// away — so it is written in here rather than found among the members.
		if (factory.Accumulator is { Length: > 0 } accumulator)
			parameters.Add($"{graph.Types[rule]} {accumulator}");

		foreach (var member in factory.Members)
			if (member.Name != "text" && member.Name != factory.Accumulator)
				parameters.Add(
					results.ValueOf(member.Rule) +

					// A fold step is applied once per iteration and is handed that
					// iteration's captures, so what collects for the rule arrives here as
					// one of what it collected.
					(member.IsSequence && factory.Accumulator is null ? "[]" :
						member.IsOptional ? "?" : "") +

					" " + ResultTypes.ParameterOf(member));

		file.Line($"/// <summary>What <c>{rule.Name}</c> builds its value with (docs/syntax.md §7.3).</summary>");
		file.Line($"static {graph.Types[rule]} {factory.Method}({string.Join(", ", parameters)}) =>");
		file.Line("\t" + ((Node.Construct)factory.Of).Text + ";");
	}

	/// <summary>
	/// The repetition of a rule that was marked <c>recover</c>, the slot its elements
	/// collect into, and what it was told (§8.2).
	/// </summary>
	static (Node Repetition, Recovery Recovery, int Slot)? RecoveryIn(
		RecognitionGraph graph, ResultTypes results, RuleSymbol rule)
	{
		if (graph.Recoveries.Count == 0)
			return null;

		var layout = LayoutOf(graph, results, rule);

		return Find(graph.Bodies[rule], -1);

		// The capture is where a recovered element goes: the same sequence its successful
		// siblings collect into. It may be either side of the quantifier — `rows: Row*` is
		// `(rows: Row)*`, because a capture binds tighter (§10) — so both are looked at.
		(Node, Recovery, int)? Find(Node node, int slot)
		{
			if (node is Node.Repeat(var repeated, _, _) && graph.Recoveries.TryGetValue(node, out var recovery))
				return (node, recovery, slot >= 0 ? slot : repeated is Node.Capture ? layout.SlotOf(repeated) : -1);

			if (node is Node.Capture(_, var captured))
				return Find(captured, layout.SlotOf(node));

			foreach (var child in Children(node))
				if (Find(child, -1) is { } found)
					return found;

			return null;
		}
	}

	static IEnumerable<Node> Children(Node node) => node switch
	{
		Node.Sequence(var nodes)     => nodes,
		Node.Choice(var nodes)       => nodes,
		Node.Repeat(var body, _, _)  => [body],
		Node.Construct(var body, _)  => [body],
		_                            => [],
	};

	/// <summary>
	/// What a broken element becomes: the C# the <c>recover</c> named, with the extent it
	/// covered and where in the sequence it was.
	/// </summary>
	static void EmitRecoveryFactory(
		Writer file, ResultTypes results, RuleSymbol rule, string owner, Recovery recovery,
		RecognitionGraph graph, int slot)
	{
		var element    = LayoutOf(graph, results, rule).Slots[slot].Rule;
		var parameters = new List<string>();

		foreach (var name in recovery.Asks)
			parameters.Add(TypeOfSupplied(name) + " " + name);

		file.Line($"/// <summary>What <c>{rule.Name}</c> makes of an element it could not read.</summary>");
		file.Line(
			$"static {results.ValueOf(element)} {owner}_Recover({string.Join(", ", parameters)}) =>");
		file.Line("\t" + recovery.Factory + ";");
		file.Line();
	}

	/// <summary>Whether any <c>recover</c> in this grammar asked where its element was.</summary>
	static bool Locating(RecognitionGraph graph)
	{
		foreach (var recovery in graph.Recoveries.Values)
		{
			var asked = recovery.Asks;

			if (asked.Contains("line") || asked.Contains("column"))
				return true;
		}

		return false;
	}

	/// <summary>The C# type of a name §8.2 supplies to a failure factory.</summary>
	static string TypeOfSupplied(string name) => name switch
	{
		"text" or "message" => "string",
		"span"              => "global::DotGram.SourceSpan",
		_                   => "int",
	};

	/// <summary>One rule, and whether it needed the shared stack helper.</summary>
	static bool EmitRule(Writer file, RecognitionGraph graph, ResultTypes results, RuleSymbol rule)
	{
		var machine = new Machine(MethodOf(rule), results, BuiltBy(graph, results, rule))
		{
			Reaches = graph.Recoveries.Count > 0,
		};

		if (RecoveryIn(graph, results, rule) is var (repetition, recovery, slot))
		{
			machine.Recovers(repetition, recovery, slot, MethodOf(rule) + "_Recover");

			if (recovery.Factory is not null && slot >= 0)
				EmitRecoveryFactory(file, results, rule, MethodOf(rule), recovery, graph, slot);
		}

		var entry   = machine.Compile(graph.Bodies[rule], Machine.Accept);
		var text    = machine.Render(entry, $"{rule.Name} = {graph.Bodies[rule]}");

		foreach (var extra in machine.Extra)
		{
			file.Write(extra);
			file.Line();
		}

		file.Write(text);

		return machine.UsesStack || machine.Extra.Count > 0;
	}

	internal static string MethodOf(RuleSymbol rule) => "Recognize_" + IdentifierOf(rule);

	/// <summary>
	/// A rule's name as one C# identifier, unique across the grammar.
	/// </summary>
	/// <remarks>
	/// The short name is not unique and is not meant to be — shadowing is what a scope is
	/// for, so a grammar with a <c>Trivia</c> per scope is the ordinary case rather than a
	/// clash. The scopes a rule is declared in are prefixed to tell them apart, named
	/// rather than numbered so that a reader of the generated code can still see which
	/// rule a method came from. The standard library's scope is not an identifier and is
	/// left off: its names are fixed, and a grammar that shadows one of them takes the
	/// name with it.
	/// </remarks>
	internal static string IdentifierOf(RuleSymbol rule)
	{
		var name = rule.Name;

		for (var scope = rule.Scope; scope is { Name.Length: > 0 }; scope = scope.Parent)
			if (IsIdentifier(scope.Name))
				name = scope.Name + "_" + name;

		return name;
	}

	static bool IsIdentifier(string name)
	{
		foreach (var c in name)
			if (!char.IsLetterOrDigit(c) && c != '_')
				return false;

		return true;
	}

	/// <summary>The recognizer that also insists the input ended — what `parse` calls.</summary>
	static string WholeOf(RuleSymbol rule) => MethodOf(rule) + "_Whole";

	/// <summary>
	/// End of input: the complement of everything, not present. The same node `eof`
	/// lowers to, built here rather than looked up so that a grammar which never
	/// mentions `eof` still gets one.
	/// </summary>
	static Node EndOfInput =>
		new Node.Lookahead(IsPositive: false, new Node.Element(IsNegated: true, [], [], []));

	/// <summary>What a publication answers with. The name a rule may not take.</summary>
	internal const string MatchType = "Match";

	/// <summary>
	/// One answer from a publication: what was recognized, or why nothing was.
	/// </summary>
	/// <remarks>
	/// <para>
	/// Unconstrained, because a rule may declare itself <c>: @int</c>. <c>Value</c> is
	/// therefore <c>T</c> and not <c>T?</c> — an unconstrained <c>T?</c> needs a language
	/// version this generator may not assume — and <c>IsSuccess</c> is what says whether
	/// there is one. On a failure it is <c>default</c>.
	/// </para>
	/// <para>
	/// One type for the whole grammar rather than one per rule: only the value differs,
	/// and a per-rule copy of the same four members would be noise in every generated
	/// file.
	/// </para>
	/// </remarks>
	internal const string MatchStruct = """
		/// <summary>What a publication answers with: the value, or why there is none.</summary>
		public readonly struct Match<T>
		{
			private Match(bool isSuccess, T value, string? error, int position, int length)
			{
				IsSuccess = isSuccess;
				Value     = value;
				Error     = error;
				Position  = position;
				Length    = length;
			}

			/// <summary>Whether there is a value.</summary>
			public bool IsSuccess { get; }

			/// <summary>What was recognized. Meaningless unless <c>IsSuccess</c>.</summary>
			public T Value { get; }

			/// <summary>Why nothing was recognized, or null.</summary>
			public string? Error { get; }

			/// <summary>Where the match began, or how far the input could be followed before it failed.</summary>
			public int Position { get; }

			/// <summary>How much was matched. Zero when nothing was.</summary>
			public int Length { get; }

			internal static Match<T> Success(T value, int position, int length)
			{
				return new Match<T>(true, value, null, position, length);
			}

			internal static Match<T> Failed(string error, int position)
			{
				return new Match<T>(false, default!, error, position, 0);
			}
		}
		""";

	/// <summary>
	/// What every recognizer carries so that a failure can be described.
	/// </summary>
	/// <remarks>
	/// The name a rule may not take: <see cref="ResultTypes"/> renames its own type
	/// instead if a grammar declares a rule called this.
	/// </remarks>
	internal const string FailureType = "Failure";

	/// <summary>
	/// The record of the best failure a match saw, threaded through every recognizer.
	/// </summary>
	/// <remarks>
	/// A struct passed by <c>ref</c> rather than more <c>out</c> parameters, and that is
	/// the point of it: what a failure has to say is going to grow — the set of what was
	/// expected there, an outcome that tells a malformed record from no record at all
	/// (docs/syntax.md §8.1) — and each of those would otherwise be another parameter on
	/// every recognizer and another edit at every call site.
	/// </remarks>
	internal static string FailureStructWith(bool reach) =>
		Lines.Normalize(FailureStruct).Replace(
			"\t{{reach}}" + Lines.Ending,
			reach ? Lines.Normalize(ReachField) + Lines.Ending : "");

	const string FailureStruct = """
		/// <summary>Where a match got before it gave up, and why.</summary>
		struct Failure
		{
			/// <summary>
			/// The furthest position the input was followed to. Zero on a match that
			/// succeeded without ever backtracking, and meaningless unless one failed.
			/// </summary>
			public int Position;
			{{reach}}
		}
		""";

	/// <summary>
	/// The field a recovering grammar needs beside <c>Position</c>, and one that does not
	/// use recovery does not carry.
	/// </summary>
	/// <remarks>
	/// <c>Position</c> is the whole parse's furthest and something further along may
	/// already have raised it, so it cannot say whether <b>this</b> element began. This
	/// one is reset where each element begins, which is exactly the question §8.2 asks.
	/// </remarks>
	const string ReachField = """

			/// <summary>How far the element a recovering repetition last began got.</summary>
			public int Reach;
		""";

	/// <summary>
	/// Grows the backtracking stack. Emitted once per class, next to the recognizers
	/// that share it.
	/// </summary>
	internal const string GrowHelper = """
		static int[] Grow(global::System.Span<int> from)
		{
			var bigger = new int[from.Length * 2];

			from.CopyTo(bigger);

			return bigger;
		}
		""";

	/// <summary>The method a factory asking for <c>line</c> or <c>column</c> is served by.</summary>
	internal const string LocateMethod = "Locate";

	/// <summary>
	/// Where a position is, for a person. Emitted once per class, and only for a grammar
	/// whose <c>recover</c> asked to be told (§8.2).
	/// </summary>
	/// <remarks>
	/// Both from 1, which is where an editor starts counting and therefore where a message
	/// a person will act on has to. <c>\r\n</c> needs no case of its own: the line ends at
	/// the <c>\n</c>, and the <c>\r</c> before it is the last column of the line it ends.
	/// </remarks>
	internal const string LocateHelper = """
		/// <summary>Which line and column a position is on, both counting from 1.</summary>
		static void Locate(global::System.ReadOnlySpan<char> text, int position, out int line, out int column)
		{
			line   = 1;
			column = 1;

			for (var at = 0; at < position; at++)
				if (text[at] == '\n')
				{
					line++;
					column = 1;
				}
				else
				{
					column++;
				}
		}
		""";

	internal static string Test(Node.Element element)
	{
		var tests = new List<string>();

		foreach (var range in element.Ranges)
			tests.Add(range.IsSingle
				? $"c == {Char(range.From)}"
				: $"(c >= {Char(range.From)} && c <= {Char(range.To)})");

		foreach (var category in element.Categories)
			// `\p{Lu}` is the regular-expression spelling; the enum member is
			// UppercaseLetter. `\p{L}` is not one category but five, so a group expands
			// into a test for each.
			foreach (var name in UnicodeCategories.Expand(category))
				tests.Add(
					"global::System.Globalization.CharUnicodeInfo.GetUnicodeCategory(c) == " +
					$"global::System.Globalization.UnicodeCategory.{name}");

		// An empty set admits nothing, and its complement admits everything. Said as
		// constants rather than as `!(false)`, so the caller can drop the test — and with
		// it the character it would otherwise read and never look at.
		if (tests.Count == 0)
			return element.IsNegated ? "true" : "false";

		var test = string.Join(" || ", tests);

		return element.IsNegated ? $"!({test})" : $"({test})";
	}

	/// <summary>
	/// A char as a C# character literal.
	/// </summary>
	/// <remarks>
	/// Everything outside plain printable ASCII goes out as <c>\uXXXX</c>. Putting the
	/// character itself into the file would work for most of them and produce a source
	/// file with a raw control character in it for the rest — and the emitted text is
	/// read by people, not only by a compiler.
	/// </remarks>
	internal static string Char(char value) => value switch
	{
		'\''                         => @"'\''",
		'\\'                         => @"'\\'",
		>= ' ' and <= '~'            => $"'{value}'",
		'\0'                         => @"'\0'",
		'\a'                         => @"'\a'",
		'\b'                         => @"'\b'",
		'\f'                         => @"'\f'",
		'\n'                         => @"'\n'",
		'\r'                         => @"'\r'",
		'\t'                         => @"'\t'",
		'\v'                         => @"'\v'",
		_                            => $@"'\u{(int)value:X4}'",
	};
