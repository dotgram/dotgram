// Writes UnicodeCategories.Table.cs, the general category of every code unit a recognizer reads,
// from the Unicode Character Database at the version pinned below:
//
//     dotnet run src/DotGram/Grammar/UnicodeCategories.generate.cs [UnicodeData.txt]
//
// Without an argument it downloads UnicodeData.txt of that version from unicode.org, the same file
// and the same version CaseFold.generate.cs reads. The generator carries the table rather than asking
// CharUnicodeInfo, because the runtime's answer is the runtime's own Unicode version: .NET Framework
// reads Unicode 8.0, each .NET release a later one, so one grammar would generate two parsers on two
// build machines, and a parser that asked at run time would accept different characters on
// different runtimes.
//
// The table covers the Basic Multilingual Plane, the UTF-16 code units a recognizer compares: a
// range given as <..., First> and <..., Last> is every code point between, the surrogates are Cs,
// and a code point the file does not list is Cn. It is written as runs, each the code point it
// starts at and its category, numbered as System.Globalization.UnicodeCategory numbers them.

using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Net.Http;
using System.Runtime.CompilerServices;
using System.Text;

const string Version = "16.0.0";

// In the order of System.Globalization.UnicodeCategory, whose numbers the table is written in.
string[] abbreviations =
[
	"Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Zs", "Zl", "Zp", "Cc",
	"Cf", "Cs", "Co", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Cn",
];

var here   = Path.GetDirectoryName(ScriptPath())!;
var source = args.Length > 0
	? File.ReadAllText(args[0])
	: new HttpClient().GetStringAsync($"https://www.unicode.org/Public/{Version}/ucd/UnicodeData.txt").Result;

var unassigned = Array.IndexOf(abbreviations, "Cn");
var categories = new int[0x10000];

Array.Fill(categories, unassigned);

var first = -1;

foreach (var line in source.Split('\n'))
{
	var fields = line.TrimEnd('\r').Split(';');

	if (fields.Length < 15)
		continue;

	var code     = int.Parse(fields[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
	var category = Array.IndexOf(abbreviations, fields[2]);

	if (category < 0)
		throw new InvalidDataException($"U+{code:X4} has the category '{fields[2]}', which UnicodeCategory does not name.");

	if (fields[1].EndsWith(", First>", StringComparison.Ordinal))
	{
		first = code;

		continue;
	}

	var from = fields[1].EndsWith(", Last>", StringComparison.Ordinal) ? first : code;

	first = -1;

	for (var c = from; c <= code && c <= 0xFFFF; c++)
		categories[c] = category;
}

var runs = new List<(int From, int Category)>();

for (var c = 0; c <= 0xFFFF; c++)
	if (c == 0 || categories[c] != categories[c - 1])
		runs.Add((c, categories[c]));

var text = new StringBuilder();

text.Append("// <auto-generated/>\r\n");
text.Append($"// Written by UnicodeCategories.generate.cs from UnicodeData.txt, Unicode {Version}: the general\r\n");
text.Append("// category of every code unit of the Basic Multilingual Plane, as runs of where each starts and\r\n");
text.Append("// its category. Do not edit.\r\n");
text.Append("\r\n");
text.Append("using System;\r\n");
text.Append("\r\n");
text.Append("namespace DotGram.Grammar;\r\n");
text.Append("\r\n");
text.Append("public static partial class UnicodeCategories\r\n");
text.Append("{\r\n");
text.Append("\t/// <summary>The Unicode version the table below was written from.</summary>\r\n");
text.Append($"\tpublic const string UnicodeVersion = \"{Version}\";\r\n");
text.Append("\r\n");
text.Append("\t// Each category by its number in System.Globalization.UnicodeCategory.\r\n");

for (var i = 0; i < abbreviations.Length; i++)
	text.Append($"\tconst int {abbreviations[i]} = {i,2};\r\n");

text.Append("\r\n");
text.Append($"\t/// <summary>{runs.Count} runs: the code unit each starts at, and its category.</summary>\r\n");
text.Append("\tstatic readonly int[] Runs =\r\n");
text.Append("\t{\r\n");

for (var i = 0; i < runs.Count; i += 8)
{
	text.Append("\t\t");

	for (var j = i; j < Math.Min(i + 8, runs.Count); j++)
		text.Append($"0x{runs[j].From:X4}, {abbreviations[runs[j].Category]},{(j + 1 < Math.Min(i + 8, runs.Count) ? " " : "")}");

	text.Append("\r\n");
}

text.Append("\t};\r\n");
text.Append("}\r\n");

// With a byte order mark, as every .cs file here is written.
File.WriteAllText(Path.Combine(here, "UnicodeCategories.Table.cs"), text.ToString(), new UTF8Encoding(true));
Console.WriteLine($"Unicode {Version}: {runs.Count} runs over the Basic Multilingual Plane.");

static string ScriptPath([CallerFilePath] string path = "")
{
	return path;
}
